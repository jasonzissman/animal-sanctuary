#!/usr/bin/env node
// Voice clip generator (developer tool, macOS only, zero dependencies). Renders every vocab manifest entry
// (game/data/vocab.js) with the macOS `say` command to assets/voice/<file>.m4a and writes the clip paths into
// the generated game/data/voice-clips.js, which SA.vocab.applyClips() turns into entry.clip so SA.audio.say plays
// the clip (keys without a clip keep falling back to speechSynthesis).
//   node scripts/voices.js [--force] [--core] [--voice Paulina] [--list]
//   --force  re-render clips that already exist      --core  only parts, animals, biomes and phrases
//   --voice  use this voice instead of auto-picking  --list  print the planned clips and exit
// Voice preference: Paulina (es-MX), then Mónica (es-ES), then any other es_* voice.
// Clips are written as AAC with `say --data-format=aac`; if that fails, as AIFF converted with `afconvert`.
// Idempotent: existing clips are skipped, and game/data/voice-clips.js lists every clip present on disk.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CLIP_DIR = 'assets/voice';
export const CLIPS_FILE = 'game/data/voice-clips.js';
export const CORE_GROUPS = ['part', 'animal', 'biome', 'phrase', 'foodsg', 'foodpl'];
// Single keys of otherwise non-core groups that feed prompts speak ("una zanahoria"); other numbers stay full-run only.
export const CORE_KEYS = ['number:un', 'number:una'];
/** True when a vocab key belongs in the core (classroom) clip set. */
export const isCoreKey = (key) => CORE_GROUPS.includes(key.split(':')[0]) || CORE_KEYS.includes(key);
export const SIZE_BUDGET = 3 * 1024 * 1024;
const PREFERRED = ['paulina', 'monica'];

// foods.js registers the foodsg:/foodpl: keys; it needs animals (diets), which need parts and biomes.
export const MANIFEST_FILES = ['game/sa.js', 'game/data-registry.js', 'game/data/parts.js', 'game/data/biomes.js',
  'game/data/animals.js', 'game/data/vocab.js', 'game/data/foods.js'];

/** Loads the vocab manifest in a vm context: [{ key, es }]. */
export function loadManifest(root = ROOT) {
  const ctx = vm.createContext({ console });
  ctx.window = ctx;
  for (const f of MANIFEST_FILES) {
    vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
  }
  return ctx.window.SA.data.all('vocab').map((v) => ({ key: v.key, es: v.es }));
}

/** ASCII-safe, collision-free file base name for a vocab key: 'size:pequeño' -> 'size-pequeno'. */
export function clipName(key) {
  return key.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/:/g, '-').replace(/[^A-Za-z0-9_-]+/g, '_');
}

/** Parses `say -v '?'` output into [{ name, locale }]. */
export function parseVoices(text) {
  const out = [];
  for (const line of String(text).split('\n')) {
    const m = /^(.+?)\s{2,}([a-z]{2}[_-][A-Za-z]{2})\b/.exec(line);
    if (m) out.push({ name: m[1].trim(), locale: m[2].replace('-', '_') });
  }
  return out;
}

const plain = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

/** Best Spanish voice name: Paulina, then Mónica, then any es_* voice (es_MX first); null when none. */
export function pickVoice(voices) {
  const es = voices.filter((v) => v.locale.startsWith('es_'));
  for (const want of PREFERRED) {
    const hit = es.find((v) => plain(v.name) === want);
    if (hit) return hit.name;
  }
  const other = es.find((v) => v.locale === 'es_MX') || es[0];
  return other ? other.name : null;
}

/** Contents of game/data/voice-clips.js for a { key: path } map (deterministic). */
export function renderClipsJs(map) {
  const lines = Object.keys(map).map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(map[k])}`);
  return [
    '/* GENERATED by scripts/voices.js (macOS `say`). Do not edit by hand: run `node scripts/voices.js`.',
    ' * Maps vocab keys to voice clips under assets/voice/. Loaded after game/data/vocab.js; keys without a clip',
    ' * (or clips that fail to play) fall back to speechSynthesis in SA.audio.say. */',
    '(function (root) {',
    "  'use strict';",
    '  if (root.SA && root.SA.vocab && root.SA.vocab.applyClips) {',
    '    root.SA.vocab.applyClips({' + (lines.length ? '\n' + lines.join(',\n') + '\n  ' : '') + '});',
    '  }',
    "})(typeof window !== 'undefined' ? window : globalThis);",
    ''
  ].join('\n');
}

/** Renders one clip to `dest` (AAC via say, else AIFF + afconvert). `exec(cmd, args)` runs a program. */
export function renderClip({ exec, voice, text, dest, tmpDir }) {
  const part = dest + '.part.m4a';
  try {
    exec('say', ['-v', voice, '-o', part, '--data-format=aac', text]);
    if (!fs.existsSync(part) || fs.statSync(part).size === 0) throw new Error('say wrote no AAC data');
  } catch (e) {
    fs.rmSync(part, { force: true });
    const aiff = path.join(tmpDir, path.basename(dest, '.m4a') + '.aiff');
    try {
      exec('say', ['-v', voice, '-o', aiff, text]);
      exec('afconvert', ['-f', 'm4af', '-d', 'aac', aiff, part]);
    } finally {
      fs.rmSync(aiff, { force: true });
    }
  }
  fs.renameSync(part, dest);
}

/**
 * Generates missing clips and rewrites game/data/voice-clips.js.
 * Options: root, force, core, voice, listOnly, exec (default child_process.execFileSync), log.
 * Returns { voice, rendered, skipped, failed, bytes, clips }.
 */
export function generate({ root = ROOT, force = false, core = false, voice = null, listOnly = false,
  exec = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8' }), log = () => {} } = {}) {
  let entries = loadManifest(root);
  if (core) entries = entries.filter((e) => isCoreKey(e.key));
  const names = new Map();
  for (const e of entries) {
    const n = clipName(e.key);
    if (names.has(n)) throw new Error(`voices: clip name collision: ${e.key} / ${names.get(n)}`);
    names.set(n, e.key);
  }
  const outDir = path.join(root, CLIP_DIR);
  const result = { voice: null, rendered: 0, skipped: 0, failed: [], bytes: 0, clips: {} };
  if (listOnly) {
    entries.forEach((e) => { result.clips[e.key] = `${CLIP_DIR}/${clipName(e.key)}.m4a`; });
    return result;
  }
  const exists = (e) => fs.existsSync(path.join(outDir, clipName(e.key) + '.m4a'));
  const todo = entries.filter((e) => force || !exists(e));
  if (todo.length) {
    result.voice = voice || pickVoice(parseVoices(exec('say', ['-v', '?'])));
    if (!result.voice) throw new Error('voices: no Spanish voice installed (try System Settings > Accessibility > Spoken Content)');
    fs.mkdirSync(outDir, { recursive: true });
  }
  const tmpDir = todo.length ? fs.mkdtempSync(path.join(os.tmpdir(), 'sa-voices-')) : null;
  try {
    for (const e of todo) {
      const dest = path.join(outDir, clipName(e.key) + '.m4a');
      try {
        renderClip({ exec, voice: result.voice, text: e.es, dest, tmpDir });
        result.rendered++;
        log(`rendered ${e.key}`);
      } catch (err) {
        result.failed.push(e.key);
        log(`FAILED ${e.key}: ${err.message}`);
      }
    }
  } finally {
    if (tmpDir) fs.rmSync(tmpDir, { recursive: true, force: true });
  }
  result.skipped = entries.length - todo.length;
  if (core) { // --core also drops non-core clips left over from a full run, so the repo stays small
    const keep = new Set(entries.map((e) => e.key));
    for (const e of loadManifest(root)) {
      if (!keep.has(e.key)) fs.rmSync(path.join(outDir, clipName(e.key) + '.m4a'), { force: true });
    }
  }
  // The generated file lists every clip that exists on disk (not just the ones rendered this run).
  for (const e of loadManifest(root)) {
    const file = path.join(outDir, clipName(e.key) + '.m4a');
    if (fs.existsSync(file)) {
      result.clips[e.key] = `${CLIP_DIR}/${clipName(e.key)}.m4a`;
      result.bytes += fs.statSync(file).size;
    }
  }
  fs.writeFileSync(path.join(root, CLIPS_FILE), renderClipsJs(result.clips));
  return result;
}

function main(argv) {
  const opts = { force: argv.includes('--force'), core: argv.includes('--core'), listOnly: argv.includes('--list'), log: console.log };
  const vi = argv.indexOf('--voice');
  if (vi >= 0) opts.voice = argv[vi + 1];
  const r = generate(opts);
  if (opts.listOnly) { console.log(Object.keys(r.clips).length + ' clips planned'); return 0; }
  console.log(`voice ${r.voice || '(none needed)'}: ${r.rendered} rendered, ${r.skipped} skipped, ${r.failed.length} failed; ` +
    `${Object.keys(r.clips).length} clips, ${(r.bytes / 1024).toFixed(0)} KB total`);
  if (r.bytes > SIZE_BUDGET) console.log('Clips exceed ~3 MB: re-run with --core (it removes the non-core clips).');
  return r.failed.length ? 1 : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) { console.error(e.message); process.exitCode = 1; }
}
